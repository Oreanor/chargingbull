/** First Aug trading day — start of the 3-month drawdown window. */
export const BM_AUG_I = BM_OHLC.findIndex((r) => r[0] >= '1987-08-01');

/** Black Monday itself — the column the «−20.5%» plate hangs off. */
export const BM_CRASH_I = BM_OHLC.findIndex((r) => r[0] === '1987-10-19');


/** Opener candle intro is a DESIGNED fixed frame (CandleIntro) — it stays on the crash
 *  window, Aug 1 → Black Monday. Pinned to that end date rather than to the end of the
 *  series, so lengthening the series for the chart stage can't quietly add candles to it. */
export const BM_OHLC_OPENER: OHLCRow[] =
  BM_OHLC.slice(BM_AUG_I, BM_OHLC.findIndex((r) => r[0] > '1987-10-19'));

/** Candle-chart SVG Y from absolute price. Reads the first and last tick, so extending the
 *  scale (Desktop-36's 325…225 plus our 200 section) re-maps every candle by itself. */
export function bmPriceSvgY(price: number): number {
  const hi = BM_GEOM.ticks[0], lo = BM_GEOM.ticks[BM_GEOM.ticks.length - 1];
  return hi.y + (hi.v - price) / (hi.v - lo.v) * (lo.y - hi.y);
}

/**
 * t along the drawdown axis: Aug 1 → the end of the window (November) fills [0,1].
 * Pre-Aug indices are < 0 — they exit left under the plot mask.
 */
export function bmDrawdownT(i: number): number {
  const nDD = BM_OHLC.length - BM_AUG_I;
  return nDD <= 1 ? 0 : (i - BM_AUG_I) / (nDD - 1);
}

const MONTH_ABBR = ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'];

/**
 * First trading day of each month in BM_OHLC.slice(start), as t∈[0,1] across that slice.
 * Labels are read off the dates rather than listed by hand — the old pair of functions
 * hard-coded «AUG, SEP, OCT», so extending the series to November silently dropped the
 * new month from the axis instead of labelling it.
 */
function monthMarksFrom(start: number): { l: string; t: number }[] {
  const n = BM_OHLC.length - start;
  const marks: { l: string; t: number }[] = [];
  let seen = '';
  for (let i = start; i < BM_OHLC.length; i++) {
    const ym = BM_OHLC[i][0].slice(0, 7);
    if (ym === seen) continue;
    seen = ym;
    marks.push({ l: MONTH_ABBR[+ym.slice(5, 7) - 1], t: n <= 1 ? 0 : (i - start) / (n - 1) });
  }
  return marks;
}

/** Month markers on the drawdown axis (Aug→Nov) — the window the candle stage draws. */
export const bmDrawdownMonthMarks = () => monthMarksFrom(BM_AUG_I);
